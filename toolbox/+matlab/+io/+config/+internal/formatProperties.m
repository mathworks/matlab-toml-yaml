function props = formatProperties(format)
    %formatProperties Format metadata properties accepted by setformat.
    %   props = formatProperties(format) returns a struct whose fields are
    %   the property names for "toml" or "yaml" and whose values list the
    %   allowed settings. "auto" clears a property. Comments takes text.
    %
    %   Property names match the writetoml/writeyaml options they override.

    arguments
        format (1,1) string {mustBeMember(format, ["toml", "yaml"])}
    end

    if format == "toml"
        props = struct( ...
            "ArrayStyle",        ["auto", "flow", "block"], ...
            "TableStyle",        ["auto", "expanded", "inline", "dotted"], ...
            "TableArrayStyle",   ["auto", "expanded", "inline"], ...
            "StringEscapeStyle", ["auto", "escaped", "literal"], ...
            "StringLayout",      ["auto", "singleline", "multiline"], ...
            "IntegerFormat",     ["auto", "dec", "hex", "oct", "bin"], ...
            "FloatFormat",       ["auto", "fixed", "scientific"], ...
            "Comments",          string.empty);
    else
        props = struct( ...
            "ContainerStyle", ["auto", "block", "flow"], ...
            "ScalarStyle",    ["auto", "plain", "single-quoted", ...
                               "double-quoted", "literal", "folded"], ...
            "KeyStyle",       ["auto", "plain", "single-quoted", "double-quoted"]);
    end
end
